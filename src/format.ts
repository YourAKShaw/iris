import type { IrisResult } from './pipeline.js';
import { charClass } from './chars.js';

/**
 * Renders results for the terminal and as Markdown.
 * All text originates from a third-party website or a model, so terminal output strips
 * control characters (ANSI escape injection) before adding Iris's own styling.
 */

const CONTROL_CHARS = charClass([
  [0x00, 0x08], // C0 controls except tab and newline
  [0x0b, 0x1f], // includes ESC, which starts ANSI sequences
  [0x7f, 0x9f], // DEL and C1 controls
  [0x200b, 0x200f], // zero-width and directional marks
  [0x2028, 0x202e], // line/paragraph separators, bidi embeddings and overrides
  [0x2066, 0x2069], // bidi isolates
]);

export function safeText(value: string): string {
  return value.replace(CONTROL_CHARS, '');
}

interface Palette {
  bold: (s: string) => string;
  dim: (s: string) => string;
  accent: (s: string) => string;
  good: (s: string) => string;
  warn: (s: string) => string;
}

function palette(color: boolean): Palette {
  const wrap = (open: number, close: number) => (s: string) => (color ? `\u001B[${open}m${s}\u001B[${close}m` : s);
  return {
    bold: wrap(1, 22),
    dim: wrap(2, 22),
    accent: wrap(36, 39),
    good: wrap(32, 39),
    warn: wrap(33, 39),
  };
}

function wrapText(text: string, width: number, indent = ''): string {
  return text
    .split('\n')
    .map((paragraph) => {
      if (!paragraph.trim()) return '';
      const lines: string[] = [];
      let line = '';
      for (const word of paragraph.split(/\s+/).filter(Boolean)) {
        if (line && line.length + word.length + 1 > width) {
          lines.push(line);
          line = word;
        } else {
          line = line ? `${line} ${word}` : word;
        }
      }
      if (line) lines.push(line);
      return lines.map((l) => indent + l).join('\n');
    })
    .join('\n');
}

export function shortUrl(url: string): string {
  try {
    const parsed = new URL(url);
    const path = parsed.pathname === '/' ? '' : parsed.pathname.replace(/\/$/, '');
    return `${parsed.hostname.replace(/^www\./, '')}${path}`;
  } catch {
    return url;
  }
}

export function renderTerminal(result: IrisResult, options: { color: boolean; width?: number }): string {
  const c = palette(options.color);
  const width = Math.max(50, Math.min(options.width ?? 88, 100));
  const out: string[] = [];
  const rule = c.dim('─'.repeat(Math.min(width, 72)));
  const t = safeText;

  out.push('');
  out.push(`${c.accent(c.bold('IRIS'))}  ${c.bold(t(result.company.name))}`);
  out.push(wrapText(t(result.company.oneLiner), width));
  out.push('');

  out.push(
    c.bold('VERIFIED FACTS') +
      c.dim(`  ${result.stats.signalsVerified} of ${result.stats.signalsProposed} claims matched the source text`),
  );
  for (const signal of result.signals) {
    out.push(`  ${c.good('✓')} ${c.accent(signal.id.padEnd(3))} ${c.dim(signal.category.padEnd(11))} ${t(signal.claim)}`);
    out.push(c.dim(wrapText(`“${t(signal.quote)}” — ${shortUrl(signal.sourceUrl)}`, width - 8, '        ')));
  }
  if (result.dropped.length) {
    out.push(c.warn(`  ✗ ${result.dropped.length} claim(s) dropped: quote not found on the site`));
  }
  out.push('');

  if (result.hypotheses.length) {
    out.push(c.bold('HYPOTHESES') + c.dim('  inferences, not facts'));
    for (const h of result.hypotheses) {
      out.push(wrapText(`• ${t(h.statement)} ${c.dim(`(${h.basedOn.join(', ')} · ${h.confidence})`)}`, width, '  '));
    }
    out.push('');
  }

  result.emails.forEach((email, index) => {
    out.push(rule);
    out.push(`${c.bold(`EMAIL ${index + 1}`)} ${c.dim('·')} ${c.accent(t(email.angle))}  ${c.dim(`uses ${email.basedOn.join(', ')} · ${email.wordCount} words`)}`);
    out.push(`${c.dim('Subject:')} ${c.bold(t(email.subject))}`);
    out.push('');
    out.push(wrapText(t(email.body), width));
    out.push('');
  });
  out.push(rule);

  for (const warning of result.warnings) out.push(c.warn(`! ${t(warning)}`));
  out.push(c.dim(`Sources: ${result.sources.map((s) => shortUrl(s.url)).join(', ')}`));
  const tokens = result.stats.promptTokens + result.stats.completionTokens;
  out.push(
    c.dim(
      `${result.stats.model} via ${result.stats.provider} · ${result.stats.pagesRead} pages · ` +
        `${tokens.toLocaleString('en-US')} tokens · ${(result.stats.durationMs / 1000).toFixed(1)}s`,
    ),
  );
  out.push('');
  return out.join('\n');
}

export function renderMarkdown(result: IrisResult): string {
  const lines: string[] = [];
  lines.push(`# ${result.company.name}: outreach brief`);
  lines.push('');
  lines.push(`> ${result.company.oneLiner}`);
  lines.push('');
  lines.push(`Generated by Iris on ${result.generatedAt} from <${result.input.url}>.`);
  lines.push('');
  lines.push(`## Verified facts (${result.stats.signalsVerified} of ${result.stats.signalsProposed})`);
  lines.push('');
  for (const s of result.signals) {
    lines.push(`- **${s.id} · ${s.category}:** ${s.claim}  `);
    lines.push(`  “${s.quote}” ([source](${s.sourceUrl}))`);
  }
  if (result.hypotheses.length) {
    lines.push('');
    lines.push('## Hypotheses (inferences, not facts)');
    lines.push('');
    for (const h of result.hypotheses) lines.push(`- ${h.statement} _(based on ${h.basedOn.join(', ')}; ${h.confidence} confidence)_`);
  }
  lines.push('');
  lines.push('## Drafts');
  result.emails.forEach((email, index) => {
    lines.push('');
    lines.push(`### Email ${index + 1}: ${email.angle}`);
    lines.push('');
    lines.push(`**Subject:** ${email.subject}  `);
    lines.push(`_Uses ${email.basedOn.join(', ')} · ${email.wordCount} words_`);
    lines.push('');
    lines.push('```text');
    lines.push(email.body);
    lines.push('```');
  });
  if (result.warnings.length) {
    lines.push('');
    lines.push('## Warnings');
    lines.push('');
    for (const w of result.warnings) lines.push(`- ${w}`);
  }
  lines.push('');
  lines.push('---');
  lines.push(
    `Model: ${result.stats.model} (${result.stats.provider}) · Pages read: ${result.stats.pagesRead} · ` +
      `Duration: ${(result.stats.durationMs / 1000).toFixed(1)}s`,
  );
  lines.push('');
  return lines.join('\n');
}
